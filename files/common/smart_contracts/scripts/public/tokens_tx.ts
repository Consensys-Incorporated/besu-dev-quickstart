/**
 * Token + transaction type demo — ERC20, ERC721 and ERC1155 activity sent
 * across every transaction envelope the network supports, so each one can be
 * inspected in the Besu explorer.
 *
 *   type 0 — legacy        (gasPrice)
 *   type 1 — EIP-2930      (gasPrice + accessList)
 *   type 2 — EIP-1559      (maxFeePerGas / maxPriorityFeePerGas)
 *
 * Also produces: contract creations, plain ETH transfers, ERC20 Transfer/Approval
 * events, ERC721 Transfer/Approval/ApprovalForAll events, ERC1155
 * TransferSingle/TransferBatch events, burns, and a deliberately reverted tx.
 *
 * Uses two funded genesis accounts so addresses are stable between runs.
 * No Paladin involvement — purely public on-chain transactions.
 *
 * Run:
 *   cd smart_contracts
 *   npm install && npm run compile
 *   npm run tokens-tx
 */
import { ethers } from "ethers";
import path from "path";
import fs from "fs";
import { besu } from "../../keys";

// Funded in genesis.json — demo key only.
const ALICE_PRIVATE_KEY = "0xae6ae8e5ccbfb04590405997ee2d52d2b330726137b875053c36d94e974d162f";

type TxType = 0 | 1 | 2;
const TX_TYPE_NAMES: Record<TxType, string> = {
  0: "legacy",
  1: "EIP-2930",
  2: "EIP-1559",
};

interface TxRecord {
  step: string;
  type: TxType;
  hash: string;
  status: "success" | "reverted";
}
const records: TxRecord[] = [];

function loadArtifact(name: string): { abi: ethers.InterfaceAbi; bytecode: string } {
  const artifactPath = path.resolve(
    __dirname,
    `../../artifacts/contracts/${name}.sol/${name}.json`
  );
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  return { abi: artifact.abi, bytecode: artifact.bytecode };
}

const erc20 = loadArtifact("ERC20Token");
const erc721 = loadArtifact("ERC721Token");
const erc1155 = loadArtifact("ERC1155Token");

/**
 * Sets the envelope type on a tx request. Type 1 also gets an access list,
 * generated by the node with eth_createAccessList, falling back to just the
 * target address if the node returns nothing useful.
 */
async function withType(
  signer: ethers.Wallet,
  req: ethers.TransactionRequest,
  type: TxType
): Promise<ethers.TransactionRequest> {
  const typed: ethers.TransactionRequest = { ...req, type };
  if (type !== 1) return typed;

  const provider = signer.provider as ethers.JsonRpcProvider;
  let accessList: ethers.AccessList = [];
  try {
    const result = await provider.send("eth_createAccessList", [
      {
        from: signer.address,
        to: req.to,
        data: req.data,
        value: req.value != null ? ethers.toQuantity(req.value) : undefined,
      },
      "latest",
    ]);
    accessList = result.accessList ?? [];
  } catch {
    // eth_createAccessList unavailable — fall through to the default below
  }
  if (accessList.length === 0 && req.to) {
    accessList = [{ address: req.to as string, storageKeys: [] }];
  }
  typed.accessList = accessList;
  return typed;
}

async function send(
  step: string,
  signer: ethers.Wallet,
  req: ethers.TransactionRequest,
  type: TxType
): Promise<ethers.TransactionReceipt> {
  const tx = await signer.sendTransaction(await withType(signer, req, type));
  const receipt = (await tx.wait())!;
  records.push({ step, type, hash: tx.hash, status: "success" });
  console.log(`  [type ${type} ${TX_TYPE_NAMES[type]}] ${step} — txHash: ${tx.hash}`);
  return receipt;
}

async function call(
  step: string,
  signer: ethers.Wallet,
  contract: ethers.Contract,
  method: string,
  args: unknown[],
  type: TxType
): Promise<ethers.TransactionReceipt> {
  const req = await contract.getFunction(method).populateTransaction(...args);
  return send(step, signer, req, type);
}

async function deploy(
  step: string,
  signer: ethers.Wallet,
  artifact: { abi: ethers.InterfaceAbi; bytecode: string },
  args: unknown[],
  type: TxType
): Promise<ethers.Contract> {
  const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, signer);
  const req = await factory.getDeployTransaction(...args);
  const receipt = await send(step, signer, req, type);
  console.log(`    deployed at: ${receipt.contractAddress}`);
  return new ethers.Contract(receipt.contractAddress!, artifact.abi, signer);
}

async function main(): Promise<void> {
  console.log("=== TOKENS + TRANSACTION TYPES DEMO ===\n");

  // cacheTimeout -1: don't reuse cached nonces when blocks are mined faster than 250ms
  const provider = new ethers.JsonRpcProvider(besu.rpcnode.url, undefined, { cacheTimeout: -1 });
  const owner = new ethers.Wallet(besu.rpcnode.accountPrivateKey, provider);
  const alice = new ethers.Wallet(ALICE_PRIVATE_KEY, provider);
  console.log(`Owner: ${owner.address}`);
  console.log(`Alice: ${alice.address}`);

  const ONE = 10n ** 18n;

  // ── 1. Plain ETH transfers ───────────────────────────────────────────────────
  console.log("\n1. Plain ETH transfers, one per tx type ...");
  for (const type of [0, 1, 2] as TxType[]) {
    await send(`send 0.1 ETH owner -> alice`, owner, { to: alice.address, value: ethers.parseEther("0.1") }, type);
  }

  // ── 2. Deploy one contract per tx type ───────────────────────────────────────
  console.log("\n2. Deploying token contracts ...");
  const token20 = await deploy("deploy ERC20Token", owner, erc20, ["DemoToken", "DEMO", 1000n], 0);
  const token721 = await deploy("deploy ERC721Token", owner, erc721, ["DemoNFT", "DNFT"], 1);
  const token1155 = await deploy(
    "deploy ERC1155Token",
    owner,
    erc1155,
    ["https://example.com/api/item/{id}.json"],
    2
  );

  // ── 3. ERC20 ─────────────────────────────────────────────────────────────────
  console.log("\n3. ERC20 ...");
  await call("ERC20 mint 500 to owner", owner, token20, "mint", [owner.address, 500n * ONE], 2);
  await call("ERC20 transfer 200 owner -> alice", owner, token20, "transfer", [alice.address, 200n * ONE], 0);
  await call("ERC20 approve alice for 100", owner, token20, "approve", [alice.address, 100n * ONE], 1);
  await call(
    "ERC20 transferFrom owner -> alice (by alice)",
    alice,
    token20.connect(alice) as ethers.Contract,
    "transferFrom",
    [owner.address, alice.address, 100n * ONE],
    2
  );
  await call("ERC20 burn 50 (alice)", alice, token20.connect(alice) as ethers.Contract, "burn", [50n * ONE], 0);
  console.log(`    owner balance: ${ethers.formatUnits(await token20.balanceOf(owner.address), 18)} DEMO`);
  console.log(`    alice balance: ${ethers.formatUnits(await token20.balanceOf(alice.address), 18)} DEMO`);

  // ── 4. ERC721 ────────────────────────────────────────────────────────────────
  console.log("\n4. ERC721 ...");
  // token ids 0, 1, 2 — one mint per tx type
  await call("ERC721 mint #0 to owner", owner, token721, "mint", [owner.address], 0);
  await call("ERC721 mint #1 to owner", owner, token721, "mint", [owner.address], 1);
  await call("ERC721 mint #2 to alice", owner, token721, "mint", [alice.address], 2);
  await call("ERC721 transferFrom #0 owner -> alice", owner, token721, "transferFrom", [owner.address, alice.address, 0n], 1);
  await call("ERC721 approve alice for #1", owner, token721, "approve", [alice.address, 1n], 2);
  await call(
    "ERC721 safeTransferFrom #1 owner -> alice (by alice)",
    alice,
    token721.connect(alice) as ethers.Contract,
    "safeTransferFrom(address,address,uint256)",
    [owner.address, alice.address, 1n],
    0
  );
  await call(
    "ERC721 setApprovalForAll owner as operator",
    alice,
    token721.connect(alice) as ethers.Contract,
    "setApprovalForAll",
    [owner.address, true],
    1
  );
  await call("ERC721 burn #2 (by operator)", owner, token721, "burn", [2n], 2);
  console.log(`    alice owns ${await token721.balanceOf(alice.address)} DNFT`);

  // ── 5. ERC1155 ───────────────────────────────────────────────────────────────
  console.log("\n5. ERC1155 ...");
  await call("ERC1155 mint id=1 x100 to owner", owner, token1155, "mint", [owner.address, 1n, 100n], 0);
  await call(
    "ERC1155 mintBatch ids=[2,3,4] to owner",
    owner,
    token1155,
    "mintBatch",
    [owner.address, [2n, 3n, 4n], [10n, 20n, 1n]],
    1
  );
  await call(
    "ERC1155 safeTransferFrom id=1 x25 owner -> alice",
    owner,
    token1155,
    "safeTransferFrom",
    [owner.address, alice.address, 1n, 25n, "0x"],
    2
  );
  await call(
    "ERC1155 safeBatchTransferFrom ids=[2,3] owner -> alice",
    owner,
    token1155,
    "safeBatchTransferFrom",
    [owner.address, alice.address, [2n, 3n], [5n, 5n], "0x"],
    0
  );
  await call(
    "ERC1155 burn id=1 x5 (alice)",
    alice,
    token1155.connect(alice) as ethers.Contract,
    "burn",
    [alice.address, 1n, 5n],
    1
  );
  const balances: bigint[] = await token1155.balanceOfBatch(
    [alice.address, alice.address, alice.address],
    [1n, 2n, 3n]
  );
  console.log(`    alice balances ids [1,2,3]: [${balances.join(", ")}]`);

  // ── 6. Reverted transaction ──────────────────────────────────────────────────
  // gasLimit is set explicitly so ethers skips estimateGas (which would reject
  // the tx locally) and the failing tx actually gets mined.
  console.log("\n6. Reverted tx — alice tries to transfer more DEMO than she holds ...");
  const badReq = await token20
    .connect(alice)
    .getFunction("transfer")
    .populateTransaction(owner.address, 1_000_000n * ONE);
  let badHash = "";
  try {
    const badTx = await alice.sendTransaction(await withType(alice, { ...badReq, gasLimit: 100_000n }, 2));
    badHash = badTx.hash;
    await badTx.wait();
  } catch (err) {
    // Besu mines the tx with status 0 and ethers throws CALL_EXCEPTION on wait();
    // some dev nodes reject it at submission instead — either way it's expected
    badHash ||= (err as { error?: { data?: { txHash?: string } } }).error?.data?.txHash ?? "(rejected by node)";
  }
  records.push({ step: "ERC20 transfer exceeding balance", type: 2, hash: badHash, status: "reverted" });
  console.log(`  [type 2 EIP-1559] ERC20 transfer exceeding balance (reverted) — txHash: ${badHash}`);

  // ── Summary ──────────────────────────────────────────────────────────────────
  console.log("\n=== SUMMARY ===");
  console.log(`ERC20Token:   ${await token20.getAddress()}`);
  console.log(`ERC721Token:  ${await token721.getAddress()}`);
  console.log(`ERC1155Token: ${await token1155.getAddress()}\n`);
  for (const r of records) {
    console.log(`  type ${r.type} ${TX_TYPE_NAMES[r.type].padEnd(8)}  ${r.status.padEnd(8)}  ${r.hash}  ${r.step}`);
  }
  const counts = ([0, 1, 2] as TxType[]).map(
    (t) => `type ${t}: ${records.filter((r) => r.type === t).length}`
  );
  console.log(`\n  ${records.length} txs — ${counts.join(", ")}`);

  console.log("\n=== DONE ===");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
